import assert from 'node:assert/strict';
import { comparisonData, comparisonSource } from '../web/comparison-model.js';
import { periodChange, isThursday, distributionRows } from '../web/price-distribution.js';
const asOf = '2026-10-02T02:00:00Z';
const trade = daily => ({ asOf, minTrades: 5, daily });
const a = trade([{ d:'2026-09-28',median:100,n:5 },{ d:'2026-09-29',median:110,n:5 },{ d:'2026-09-30',median:120,n:5 },{ d:'2026-10-01',median:130,n:5 },{ d:'2026-10-02',median:900,n:5 }]);
const b = trade([{ d:'2026-09-29',median:200,n:5 },{ d:'2026-09-30',median:250,n:2 },{ d:'2026-10-01',median:220,n:5 }]);
const result = comparisonData([a,b],7);
assert.equal(result.from.d,'2026-09-29','공통 시작일로 맞춘다');
assert.equal(result.to.d,'2026-10-01');
assert.deepEqual(result.rows[1].values,[120,null],'희소 체결을 비교 추세에 쓰지 않는다');
assert.equal(result.rows.some(r=>r.d==='2026-10-02'),false,'오늘 미완성 제외');
assert.equal(comparisonData([a,trade([])]).from,null);
assert.equal(comparisonData([a,trade([{d:'2026-10-01',median:1,n:5}])]).to,null);
assert.equal(comparisonData([a,undefined]).rows.length,0);
assert.equal(comparisonData([a,{...b,asOf:'2026-10-01T00:00:00Z'}]).to,null,'이른 집계 시각에서 완료일 판단');
const card={price_basis:'ask0'},raw={daily:[{d:'2026-09-29',vwap:10,n:1}],max:{daily:[{d:'2026-09-29',vwap:20,n:1}]}};
assert.equal(comparisonSource(card,raw,'max',asOf).daily[0].vwap,20);
assert.equal(comparisonSource(card,{daily:raw.daily},'max',asOf).daily.length,0,'맥스업 부재를 0업으로 대체하지 않는다');
const card2={basis:'ask',asOf,daily:[{d:'2026-09-29',vwap:10,n:1},{d:'2026-09-30',vwap:0,n:1},{d:'2026-10-01',vwap:12,n:1}]};
assert.deepEqual(comparisonData([card2,card2]).rows[1].values,[null,null],'무매물을 0골드로 계산하지 않는다');
assert.equal(periodChange(distributionRows(a,'all')).last.median,130);
assert(Math.abs(periodChange(distributionRows(b,'all')).percent-10)<1e-9);
assert.equal(periodChange([]),null);
assert.equal(isThursday('2026-10-01'),true);
assert.equal(isThursday('2026-09-30'),false);
const daily=Array.from({length:40},(_,i)=>({d:new Date(Date.UTC(2026,7,23+i)).toISOString().slice(0,10),median:100+i,n:5}));
assert.equal(comparisonData([trade(daily),trade(daily)],7).rows.length,7);
console.log('아이템 비교: 공통 완료일·희소/결측·카드 단계·기간 변화·목요일 통과');
